  rigidBodyInput(object,previous=null){
    const bounds=this.objectBounds(object);
    const scale=object.transform.scale;
    if(!bounds)throw Error('Rigid collider needs measured object bounds');
    const scaled={center:{},size:{}};
    for(const axis of ['x','y','z']){
      scaled.center[axis]=bounds.center[axis]*scale[axis];
      scaled.size[axis]=bounds.size[axis]*scale[axis];
      if(!finite(scaled.size[axis],.001,20))throw Error('Rigid collider exceeds the supported size');
    }
    const config=object.rigidBody;
    if(!validRigidBodyConfig(config))throw Error('Invalid rigid body configuration');
    if(config.collider==='procedural-mesh'&&
       (object.assetId!==PROCEDURAL_ASSET_ID||!object.procedural))
      throw Error('Mesh collider needs a reviewed static procedural construction');
    const meshes=config.collider==='procedural-mesh'?
      generateProcedural(object.procedural).parts.filter(part=>
        part.collision?.kind==='static-trimesh').map(part=>({partId:part.partId,
          positions:part.geometry.positions.map((value,index)=>value*scale[['x','y','z'][index%3]]),
          indices:part.geometry.indices})):undefined;
    return {objectId:object.objectId,type:config.type,
      position:previous?.position??clone(object.transform.position),
      rotation:previous?.rotation??eulerDegreesToQuaternion(object.transform.rotation),
      bounds:scaled,restitution:config.restitution,friction:config.friction,
      sensor:config.sensor,...(meshes?{meshes}:{}),
      ...(previous&&config.type==='dynamic'?{
        linearVelocity:previous.linearVelocity,angularVelocity:previous.angularVelocity,
        ...(previous.sleeping!==undefined?{sleeping:previous.sleeping}:{})}:{})};
  }
